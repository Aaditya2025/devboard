/** Day-offset from "today" (negative = past, positive = future), so demo data (and the dashboard's completion trend) always looks current regardless of when this app is actually run. */
function daysFromToday(offset: number): string {
  const date = new Date();
  date.setDate(date.getDate() + offset);
  return date.toISOString().slice(0, 10);
}

